import fractalFunctions
import pandas as pd
import geopandas as gp
import os
import numpy as np
import sys
from concurrent.futures import ProcessPoolExecutor,as_completed, ThreadPoolExecutor


'''
Author : Lucas Villard 
Last revised : Jan 28 2025

Usage : Scripts to compute fractal algorithm on the observed and simulated_CRW trajectories.

Description :
	 The script uses the "computeVFractal"function in the fractalFunctions source script to obtain fractal statistics (mean,var and sd of D) as well as autocorrelation value
	 for a series of stepSizes (called "stepVector"). By default, The stepSize series is computed starting at 100m and geometrically increased until the third of the maximum distance 
	 between two points in the observed GPS series, with 98 steps generated in between (for a total of 100 steps). You can customize the stepVector on the dedicated section below.
	 
	 the stepVector is then recycled in the simulated CRW trajectory to generate null distribution of fractal D and autocorrelation, using 100 sampling on the CRW trajectory by changing
	 the starting point of the trajectory analysis. 
	 

--- Inputs ---

- a [animalName]_[deerYear].csv file that has been generated by the "format_GPS_data.py" script
- a corresponding Simulated_CRW_[animalName]_[deerYear].csv
- OPTIONAL : parameters for the computation of stepVector

-- Outputs ---

the script will output the statistics resulting form the fractal algorithm 
	"meanScale"/varScale" : mean and variance of the observed distance between two segmented paths 	
	 "meanFrac" /varFrac" : mean and variance of the fractal D	
	 "meanCosine /varCosine" : mean and variance of the turning angles of the rediscretized trajectory
	  "autocorrelation/pValue" : correlation coefficient of subsequent turning angles (lag=1) and associated p-value from the pearson's test.
	  
Two files are generated : one from the simulated CRW and one for the observed trajectory.


'''


if __name__=="__main__":
    with ProcessPoolExecutor(max_workers=16) as executor:
        print("\n"+"######### **** compute Fractal on observed and simulated trajectory ********* ########")

        workDir=sys.argv[2]
        fileName=os.path.splitext(os.path.basename(sys.argv[1]))[0]
        animalTest=fileName.split("_")[0]

        yearTest="_".join(fileName.split("_")[1:])
        print(f" deer : {animalTest} -- deerYear : {yearTest}")


        ##################### loading observed trajectory : this is the inFile from the bash script
        try:
            tmpObs=pd.read_csv(sys.argv[1])
            obsTraj=gp.GeoDataFrame(tmpObs, geometry=gp.GeoSeries.from_wkt(tmpObs.geometry),crs=2056)
        except FileNotFoundError as fnf:
            print("the observed trajectory file does not exist.. did you forget to generate it ?")


        ##################### loading simulated trajectory
        try:
            tmpSim=pd.read_csv(os.path.join(workDir, f"Simulated_CRW_{animalTest}_{yearTest}.csv"))
            simTraj=gp.GeoDataFrame(tmpSim, geometry=gp.points_from_xy(tmpSim["xcoord"], tmpSim["ycoord"]),crs=2056)
            simTraj.sort_values(by="dateTime", axis=0,inplace=True)
        except FileNotFoundError as fnf:
            print("the simulated trajectory file does not exist.. did you forget to generate it ?")

        ##### **** parameters that can be changed by the user **** #######
        
        initStep=100
        endStep=round(fractalFunctions.thirdHigherPointDist(obsTraj))
        nbStep=100
        stepVector=np.geomspace(initStep, endStep, nbStep)
        #stepVector=np.linspace(initStep, endStep, nbStep)
	##################################################################
        stepParam=[initStep, endStep, nbStep]

        ####### choose the number of replicates
        nrun=100
        ######
        poolStat=None
        
        poolDF = {executor.submit(fractalFunctions.fractalMultiProcess, i, simTraj, stepVector,0.15,100,True):  i for i in range(nrun)}
        for future in as_completed(poolDF):
            if poolStat is None:
                try:
                    df_stat_sim =future.result()
                    poolStat=df_stat_sim.copy()
                except Exception as exc:
                    print('%r generated an exception: %s' % (poolDF[future], exc))
            else:
                try:
                    poolStat=pd.concat([poolStat, future.result()],axis=0, ignore_index=True)
                except Exception as exc:
                    print('%r generated an exception: %s' % (poolDF[future], exc))
    print("***** simulated path fractal DONE ******")


    #### writing outputs
    resultPath=workDir
    try:
        os.mkdir(resultPath)
    except OSError as error:
        print(error)   
    poolStat.to_csv(os.path.join(resultPath,f"{animalTest}_{yearTest}_Fractal_values_{initStep}_{endStep}_{nbStep}_scales_{nrun}_simulations.csv"), index=False)    

    meanScale=[]
    varScale=[]
    meanFrac=[]
    varFrac=[]
    stepSize=[]
    meanCosine=[]
    varCosine=[]
    accCorr=[]
    pVal=[]


    print("Computing fractal statistics for observed path ...")
    for absoluteDistance in stepVector:
        try:
            step,mFrac,vFrac, mScale,vScale,mCosine,vCosine,corr,pV = fractalFunctions.computeVFractal(absoluteDistance,obsTraj,successive=True,equation_1996=False )
            meanFrac.append(mFrac)
            varFrac.append(vFrac)
            meanScale.append(mScale)
            stepSize.append(step)
            varScale.append(vScale)
            accCorr.append(corr)
            meanCosine.append(mCosine)
            varCosine.append(vCosine)
            pVal.append(pV)
        except fractalFunctions.NotEnoughPointError as nepe:
            break
    df_stat=pd.DataFrame({"prenom":obsTraj.prenom.unique()[0],
                        "deerYear": obsTraj.deerYear.unique()[0],
                        "stepSize":stepSize,
    "meanScale":meanScale,
    "varScale":varScale,
    "meanFrac":meanFrac,
    "varFrac":varFrac,
    "meanCosine":meanCosine, 
    "varCosine":varCosine, 
    "autocorrelation":accCorr,
    "pValue":pVal})

    print(" - observed path Fractal DONE -")


    df_stat.to_csv(os.path.join(resultPath,f"{animalTest}_{yearTest}_Fractal_values_{initStep}_{endStep}_{nbStep}_scales_observed_path.csv"), index=False)
    print(" - fractal statistics for the observed path DONE -")



