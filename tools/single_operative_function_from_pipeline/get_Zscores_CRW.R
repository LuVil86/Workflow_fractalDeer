coordSplit<-function(x){
  tmp<-unlist(strsplit(x, split=" "))
  if(any(grepl("Z", tmp))){
    coordX<-as.numeric(substring(tmp[3],2,nchar(tmp[3])))
    coordY<-as.numeric(tmp[4])
  }
  else{
    coordX<-as.numeric(substring(tmp[2],2,nchar(tmp[2])))
    coordY<-as.numeric(substring(tmp[3],1,nchar(tmp[3])-1))
  }
  return(list("coordX"=coordX, "coordY"=coordY))
}


###################################**************************************###############################################
###################################******* z-score for single deer ******############################################
###################################**************************************###############################################


simDeer<-paste0(selectedDeer,"_CRW")

obsFile<-paste0("./",selectedDeer,"/",list.files(path=paste0("./",selectedDeer),
                                                 pattern=paste0("^",selectedDeer,"_", selectedYear,"_Fractal_values_",".*",nbScale,"_scales_observed_path.csv") 
)
)
obs<-read.csv(obsFile, h=T)
simFile<-paste0("./",selectedDeer,"/",list.files(path=paste0("./",selectedDeer),
                                                 pattern=paste0("^",selectedDeer,"_", selectedYear,"_Fractal_values_",".*",nbScale,"_scales_",nbSim,"_simulations.csv")
)
)
  sim<-read.csv(simFile, h=T)

  m.sim<-aggregate(sim[,fractalParameter], list(sim$stepSize), mean)
  max.sim<-aggregate(sim[,fractalParameter], list(sim$stepSize), max)
  sd.sim<-aggregate(sim[,fractalParameter], list(sim$stepSize), sd)
  confint.sim<-aggregate(sim[,fractalParameter], list(sim$stepSize), quantile, probs=c(0.05, 0.95))
  var.sim<-aggregate(sim[,fractalParameter], list(sim$stepSize), var)
  if(nrow(m.sim)>nrow(obs)){
    m.sim<-m.sim[1:nrow(obs),]
    confint.sim<-confint.sim[1:nrow(obs),]
    sd.sim<-sd.sim[1:nrow(obs),]
    var.sim<-var.sim[1:nrow(obs),]
    max.sim<-max.sim[1:nrow(obs),]
  }else{
    obs<-obs[1:nrow(m.sim),]
  }
  
  
  sumStat.sim<-data.frame(stepSize=confint.sim$Group.1,
                          obs=obs[,fractalParameter], 
                          meanSim=m.sim$x,
                          sdSim=sd.sim$x,
                          varSim=var.sim$x,
                          lowConf=confint.sim$x[,1], 
                          upConf=confint.sim$x[,2],
                          max=max.sim$x)
  
  
  ############### z-score calculation method ########
  if(zScoreMethod=="classic"){
    
    zscore<-apply(sumStat.sim, 1, function(x) c(x["obs"]-x["meanSim"]) / c(x["sdSim"]) )
    
  }else if (zScoreMethod=="up-quantile"){
    
    zscore<-apply(sumStat.sim, 1, function(x) return(x["obs"]-x["upConf"]))
    
  }else if (zScoreMethod=="max"){
    
    zscore<-apply(sumStat.sim, 1, function(x) return(x["obs"]-x["max"]))
    
  }else{
    stop("unknown zScoreMethod parameter")
  }
  
  
  zsDF<-data.frame(prenom=rep(selectedDeer, length(zscore)),
                   deerYear=rep(selectedYear,length(zscore)),
                   stepSize=sumStat.sim$stepSize,
                   obs=sumStat.sim$obs,
                   zscore=zscore)
  
  ### thresholding : we can keep certain limits of stepSize if needed
  zsDF.thr.stepsize<-zsDF[zsDF$stepSize>=lowThr & zsDF$stepSize<upThr,]
  ### second thresholding : we keep stepSizes in function of a certain zscore values for further classifications 
  if(zScoreMethod=="classic"){
    zsDF.thr.zscore<-zsDF.thr.stepsize[which(zsDF.thr.stepsize$zscore>=quantile(zsDF.thr.stepsize$zscore, 0.95)),]
    write.csv(zsDF.thr.zscore, file=paste0("./",selectedDeer,"/",selectedDeer,"_",selectedYear,"_candidate_stepSizes_from_traditional_zscores.csv"), row.names=F)
  }else if (zScoreMethod=="up-quantile"){
    zsDF.thr.zscore<-zsDF.thr.stepsize[which(zsDF.thr.stepsize$zscore>0),]
    write.csv(zsDF.thr.zscore, file=paste0("./",selectedDeer,"/",selectedDeer,"_",selectedYear,"_candidate_stepSizes_from_upConf.csv"), row.names=F)
  }else{
    stop("unknown zScoreMethod parameter")
  }
  
  
