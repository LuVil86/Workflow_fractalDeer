# Usage : calculate  the deviance (aka "zscores") between the collection of autocorrelation values from a CRW and the observed autocorrelation (from GPS fixes)
# 	  Z-scores can be calculated in different manners (see input parameters)

### ---Input---
# - the dataframe output from the "compute_fractal_observed_and_simulated_path.py". Both observed and simulated_CRW. They are automatically searched when you specify 
#   the animalName and deerYear in the "** input parameters** " section and will produce error if it cannot find them
# - the fractal statistic you want to calculate Z-score on (by default it's the autocorrelation)
# - the way to calculate Z-score ("traditional" is the equation of z-score published elsewhere, "up-quantile" is the positive deviance from the 95% quantile of the CRW
#   distribution, "max" and "absolute" are still under development
# - "lowThr" and "upThr" are the boundaries of stepSize you want to analyze. if you have only 100 stepSizes as generated by default in the fractal script
#    you can keep it by default but sometimes for small stepSizes (i.e less than 300 for the redDeer), it is meaningless to calculate z-score so
#    you can drop them
### --output ---
## a dataframe similar to the input, but added with the "z-score" column and filtered according to the candidate stepSizes models :
###  - "classic" will return the stepSizes models above the 95% quantile of the z-score distribution
###  - "up_quantile" will return every stepSizes models with positive z-scores 

###################################################################



#####  ** input parameters ** ######
selectedDeer<-"20074"
selectedYear<-"deerYear_2011-2012_denoised"
nbScale=2000
nbSim=100
fractalParameter<-"autocorrelation"
lowThr<-300 
upThr<-Inf
zScoreMethod<-"classic" ## "classic", "up-quantile" ("max" and  "absolute" not yet implemented)
